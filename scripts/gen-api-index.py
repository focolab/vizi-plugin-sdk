#!/usr/bin/env python3
"""Write docs/reference.md: every public name of `vizi_plugin_sdk`, grouped by
what it is, with the first paragraph of its docstring.

    python scripts/gen-api-index.py           # rewrite docs/reference.md
    python scripts/gen-api-index.py --check   # fail if it is out of date

The guide explains the SDK by task; this index makes sure that every public
name can be found from the guide at all.
"""

import inspect
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import vizi_plugin_sdk as sdk  # noqa: E402

OUT = ROOT / "docs" / "reference.md"

def kind(obj) -> str:
    if inspect.ismodule(obj):
        return "module"
    if inspect.isclass(obj):
        return "class"
    if callable(obj):
        return "function"
    return "constant"


def summary(obj) -> str:
    if kind(obj) == "constant":
        return f"`{obj!r}`"
    doc = inspect.getdoc(obj) or ""
    first = doc.strip().split("\n\n")[0]
    text = " ".join(first.split())
    # Sphinx roles read badly in Markdown; keep the name they wrap.
    text = re.sub(r":(?:class|func|meth|attr|data|mod):`~?([^`]+)`", r"`\1`", text)
    text = text.replace("``", "`")
    return text or "(no summary)"


def render() -> str:
    names = sorted(getattr(sdk, "__all__", None) or [n for n in dir(sdk) if not n.startswith("_")])
    rows = {k: [] for k in ("class", "function", "constant", "module")}
    for name in names:
        obj = getattr(sdk, name)
        cell = summary(obj).replace("|", "\\|")
        rows[kind(obj)].append(f"| `{name}` | {cell} |")
    out = [
        "# API index",
        "",
        "Every public name in `vizi_plugin_sdk`, with the first paragraph of its",
        "docstring. The rest of the guide explains these by task; the docstrings",
        "are the reference. Generated by `scripts/gen-api-index.py`.",
        "",
    ]
    for title, key in (("Classes", "class"), ("Functions and decorators", "function"),
                       ("Constants", "constant"), ("Modules", "module")):
        if not rows[key]:
            continue
        out += [f"## {title}", "", "| Name | Summary |", "|---|---|", *rows[key], ""]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/reference.md is out of date: run scripts/gen-api-index.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

"""The SDK's version moves when the SDK does.

``__version__`` is ``1.0a<round>``, and it is bumped with ANY change to the
package -- not only a wire-breaking one.  Two different wheels shared the name
``1.0a1`` across six rounds, and nothing but a hash in a plugin's lock told
them apart.  ``_version_manifest.py`` beside this file records the sha256 of
every shipped file at the version it was generated for; ``test_version.py``
fails when a file differs from its record while the version does not.

Regenerate from vizi's tree, after bumping ``__version__``::

    make sdk-version-manifest
"""

from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
if str(_HERE) not in sys.path:
    sys.path.insert(0, str(_HERE))

import _layout  # noqa: E402

MANIFEST = _HERE / "_version_manifest.py"
VERSION_FORM = re.compile(r"^1\.0a[1-9][0-9]*$")
REGENERATE = "make sdk-version-manifest"


def shipped_files() -> list[Path]:
    """What a wheel carries: the package's modules and its generated stubs
    (they are shipped, so a regenerated stub is a changed SDK)."""
    package = _layout.PACKAGE
    return sorted([*package.glob("*.py"), *package.glob("_proto/*.py")])


def current_hashes() -> dict[str, str]:
    """sha256 per shipped file, over LF line endings: a Windows checkout with
    ``core.autocrlf`` holds the same source under different bytes."""
    out = {}
    for path in shipped_files():
        data = path.read_bytes().replace(b"\r\n", b"\n")
        out[path.relative_to(_layout.PACKAGE).as_posix()] = hashlib.sha256(data).hexdigest()
    return out


def current_version() -> str:
    """Read from the source, not imported: the file is the thing versioned."""
    text = (_layout.PACKAGE / "__init__.py").read_text(encoding="utf-8")
    found = re.search(r'^__version__ = "([^"]+)"$', text, re.MULTILINE)
    if found is None:
        raise AssertionError("vizi_plugin_sdk/__init__.py carries no __version__ line")
    return found.group(1)


def changed(recorded: dict[str, str], now: dict[str, str]) -> list[str]:
    """Every file added, removed or edited since the record, by name."""
    return sorted(
        name for name in recorded.keys() | now.keys() if recorded.get(name) != now.get(name)
    )


def render(version: str, hashes: dict[str, str]) -> str:
    lines = [
        '"""Generated by `make sdk-version-manifest`; do not edit.  See `_version_guard.py`."""',
        "",
        f'VERSION = "{version}"',
        "FILES = dict(",
        "    [",
    ]
    # One pair over four lines: the form black leaves alone at any name length.
    for name in sorted(hashes):
        lines += [
            "        (",
            f'            "{name}",',
            f'            "{hashes[name]}",',
            "        ),",
        ]
    lines += ["    ]", ")", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if argv != ["--write"]:
        print("usage: _version_guard.py --write", file=sys.stderr)
        return 2
    version = current_version()
    if not VERSION_FORM.match(version):
        print(f"__version__ is {version!r}; it must read 1.0a<round>", file=sys.stderr)
        return 1
    MANIFEST.write_text(render(version, current_hashes()), encoding="utf-8", newline="\n")
    print(f"wrote {MANIFEST.name} for vizi-plugin-sdk {version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

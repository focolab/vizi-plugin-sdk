//! Generates the region message types (`pois_math.v1`) from their descriptors.
//!
//! Each message becomes a struct with the fields prost would generate, the
//! same accessors for enum and optional fields, and an `unknown_fields` member
//! that keeps every field record the message does not know. The
//! `prost::Message` implementation decodes and encodes known fields with
//! prost's own encoding functions, in the order prost-derive uses, and writes
//! the unknown records after them. prost generates the package's enums and
//! service; every message is mapped to the generated struct with
//! `extern_path`.

use prost_types::FileDescriptorSet;
use std::collections::HashMap;
use std::fmt::Write as _;

pub const PACKAGE: &str = "pois_math.v1";

/// Proto names (`.pois_math.v1.Roi`) of every message in the package.
pub fn messages(fds: &FileDescriptorSet) -> Vec<String> {
    files(fds)
        .flat_map(|file| &file.message_type)
        .map(|m| format!(".{PACKAGE}.{}", m.name()))
        .collect()
}

fn files(fds: &FileDescriptorSet) -> impl Iterator<Item = &prost_types::FileDescriptorProto> {
    fds.file.iter().filter(|f| f.package() == PACKAGE)
}

/// What a field holds, as the generated code sees it.
enum Scalar {
    /// prost encoding module, Rust type, numeric.
    Plain(&'static str, &'static str, bool),
    Enum(String),
}

enum Shape {
    Scalar(Scalar),
    Message(String),
    Map { key: Scalar, value: Value },
}

enum Value {
    Scalar(Scalar),
    Message(String),
}

enum Card {
    /// proto3 implicit presence.
    Plain,
    Optional,
    Repeated {
        packed: bool,
    },
}

struct Field {
    name: String,
    ident: String,
    tag: u32,
    shape: Shape,
    card: Card,
    doc: String,
}

pub fn generate(fds: &FileDescriptorSet) -> String {
    let mut out = String::from(
        "// This file is generated by build.rs from the region descriptors.\n\
         // Each message keeps the field records it does not know and writes them\n\
         // back after its known fields.\n",
    );
    for file in files(fds) {
        let docs = comments(file);
        let enums: Vec<String> = file
            .enum_type
            .iter()
            .map(|e| format!(".{PACKAGE}.{}", e.name()))
            .collect();
        for (i, message) in file.message_type.iter().enumerate() {
            let path = vec![4, i as i32];
            message_type(&mut out, message, &path, &docs, &enums);
        }
    }
    out
}

fn message_type(
    out: &mut String,
    message: &prost_types::DescriptorProto,
    path: &[i32],
    docs: &HashMap<Vec<i32>, String>,
    enums: &[String],
) {
    let name = message.name();
    assert!(
        name.chars().next().is_some_and(|c| c.is_ascii_uppercase()) && !name.contains('_'),
        "region generator: message name {name} is not UpperCamelCase"
    );
    let entries: HashMap<String, &prost_types::DescriptorProto> = message
        .nested_type
        .iter()
        .map(|nested| {
            assert!(
                nested.options.as_ref().is_some_and(|o| o.map_entry()),
                "region generator: nested message {name}.{} is not supported",
                nested.name()
            );
            (format!(".{PACKAGE}.{name}.{}", nested.name()), nested)
        })
        .collect();
    assert!(
        message.enum_type.is_empty(),
        "region generator: nested enum in {name} is not supported"
    );
    let mut fields = Vec::new();
    for (j, f) in message.field.iter().enumerate() {
        let mut fpath = path.to_vec();
        fpath.extend([2, j as i32]);
        let proto3_optional = f.proto3_optional();
        assert!(
            f.oneof_index.is_none() || proto3_optional,
            "region generator: oneof field {name}.{} is not supported",
            f.name()
        );
        let repeated = f.label().as_str_name() == "LABEL_REPEATED";
        let ty = f.r#type().as_str_name();
        let shape = if ty == "TYPE_MESSAGE" {
            match entries.get(f.type_name()) {
                Some(entry) => {
                    let key = scalar(&entry.field[0], enums, name);
                    let v = &entry.field[1];
                    let value = if v.r#type().as_str_name() == "TYPE_MESSAGE" {
                        Value::Message(local(v.type_name(), name))
                    } else {
                        Value::Scalar(scalar(v, enums, name))
                    };
                    Shape::Map { key, value }
                }
                None => Shape::Message(local(f.type_name(), name)),
            }
        } else {
            Shape::Scalar(scalar(f, enums, name))
        };
        let card = if matches!(shape, Shape::Map { .. }) {
            Card::Plain
        } else if repeated {
            let numeric = match &shape {
                Shape::Scalar(Scalar::Plain(_, _, numeric)) => *numeric,
                Shape::Scalar(Scalar::Enum(_)) => true,
                _ => false,
            };
            let explicit = f.options.as_ref().and_then(|o| o.packed);
            Card::Repeated {
                packed: numeric && explicit.unwrap_or(true),
            }
        } else if proto3_optional {
            Card::Optional
        } else {
            Card::Plain
        };
        let field_name = f.name().to_owned();
        assert!(
            field_name
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
                && field_name != "unknown_fields",
            "region generator: field name {name}.{field_name} is not supported"
        );
        fields.push(Field {
            ident: ident(&field_name),
            name: field_name,
            tag: f.number() as u32,
            shape,
            card,
            doc: docs.get(&fpath).cloned().unwrap_or_default(),
        });
    }

    // Struct.
    out.push_str(docs.get(path).map(String::as_str).unwrap_or(""));
    out.push_str("#[derive(Clone, PartialEq, Default, Debug)]\npub struct ");
    out.push_str(name);
    out.push_str(" {\n");
    for f in &fields {
        out.push_str(&indent(&f.doc));
        let _ = writeln!(out, "    pub {}: {},", f.ident, rust_type(f));
    }
    out.push_str(
        "    /// Field records this build does not know, kept as received and\n\
         \x20   /// encoded after the known fields.\n\
         \x20   pub unknown_fields: crate::proto::UnknownFields,\n}\n",
    );

    // prost::Message. Like prost-derive, encode in field-number order.
    let mut by_tag: Vec<&Field> = fields.iter().collect();
    by_tag.sort_by_key(|f| f.tag);
    let _ = writeln!(out, "impl ::prost::Message for {name} {{");
    out.push_str(
        "    #[allow(unused_variables)]\n\
         \x20   fn encode_raw(&self, buf: &mut impl ::prost::bytes::BufMut) {\n",
    );
    for f in &by_tag {
        out.push_str(&encode(f));
    }
    out.push_str("        self.unknown_fields.encode(buf);\n    }\n");
    out.push_str(
        "    #[allow(unused_variables)]\n\
         \x20   fn merge_field(\n\
         \x20       &mut self,\n\
         \x20       tag: u32,\n\
         \x20       wire_type: ::prost::encoding::WireType,\n\
         \x20       buf: &mut impl ::prost::bytes::Buf,\n\
         \x20       ctx: ::prost::encoding::DecodeContext,\n\
         \x20   ) -> ::core::result::Result<(), ::prost::DecodeError> {\n",
    );
    if fields.is_empty() {
        out.push_str("        self.unknown_fields.merge(tag, wire_type, buf)\n    }\n");
    } else {
        out.push_str("        match tag {\n");
        for f in &fields {
            let _ = writeln!(
                out,
                "            {} => {}.map_err(|mut error| {{\n\
             \x20               error.push({name:?}, {:?});\n\
             \x20               error\n\
             \x20           }}),",
                f.tag,
                merge(f),
                f.name
            );
        }
        out.push_str(
            "            _ => self.unknown_fields.merge(tag, wire_type, buf),\n        }\n    }\n",
        );
    }
    out.push_str("    fn encoded_len(&self) -> usize {\n        self.unknown_fields.len()");
    for f in &fields {
        let _ = write!(out, "\n            + {}", encoded_len(f));
    }
    out.push_str("\n    }\n");
    out.push_str("    fn clear(&mut self) {\n        *self = ::core::default::Default::default();\n    }\n}\n");

    // Accessors prost-derive emits for enum and optional fields.
    let methods: String = fields.iter().map(accessors).collect();
    if !methods.is_empty() {
        let _ = write!(out, "impl {name} {{\n{methods}}}\n");
    }
}

fn scalar(f: &prost_types::FieldDescriptorProto, enums: &[String], owner: &str) -> Scalar {
    let ty = f.r#type().as_str_name();
    let plain = |m, t, n| Scalar::Plain(m, t, n);
    match ty {
        "TYPE_DOUBLE" => plain("double", "f64", true),
        "TYPE_FLOAT" => plain("float", "f32", true),
        "TYPE_INT32" => plain("int32", "i32", true),
        "TYPE_INT64" => plain("int64", "i64", true),
        "TYPE_UINT32" => plain("uint32", "u32", true),
        "TYPE_UINT64" => plain("uint64", "u64", true),
        "TYPE_SINT32" => plain("sint32", "i32", true),
        "TYPE_SINT64" => plain("sint64", "i64", true),
        "TYPE_FIXED32" => plain("fixed32", "u32", true),
        "TYPE_FIXED64" => plain("fixed64", "u64", true),
        "TYPE_SFIXED32" => plain("sfixed32", "i32", true),
        "TYPE_SFIXED64" => plain("sfixed64", "i64", true),
        "TYPE_BOOL" => plain("bool", "bool", true),
        "TYPE_STRING" => plain("string", "::prost::alloc::string::String", false),
        "TYPE_BYTES" => plain("bytes", "::prost::alloc::vec::Vec<u8>", false),
        "TYPE_ENUM" => {
            assert!(
                enums.iter().any(|e| e == f.type_name()),
                "region generator: enum {} of {owner} is outside {PACKAGE}",
                f.type_name()
            );
            Scalar::Enum(local(f.type_name(), owner))
        }
        other => panic!(
            "region generator: field {owner}.{} has unsupported type {other}",
            f.name()
        ),
    }
}

/// `.pois_math.v1.Vec3` -> `Vec3`; the types live in one module.
fn local(type_name: &str, owner: &str) -> String {
    let prefix = format!(".{PACKAGE}.");
    let name = type_name.strip_prefix(&prefix).unwrap_or_else(|| {
        panic!("region generator: {owner} refers to {type_name}, outside {PACKAGE}")
    });
    assert!(
        !name.contains('.'),
        "region generator: {owner} refers to nested type {type_name}"
    );
    name.to_owned()
}

fn ident(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern",
        "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
        "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use",
        "where", "while", "abstract", "become", "box", "do", "final", "gen", "macro", "override",
        "priv", "try", "typeof", "unsized", "virtual", "yield",
    ];
    if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_owned()
    }
}

fn scalar_type(s: &Scalar) -> &str {
    match s {
        Scalar::Plain(_, t, _) => t,
        Scalar::Enum(_) => "i32",
    }
}

fn scalar_module(s: &Scalar) -> &'static str {
    match s {
        Scalar::Plain(m, _, _) => m,
        Scalar::Enum(_) => "int32",
    }
}

fn rust_type(f: &Field) -> String {
    let inner = match &f.shape {
        Shape::Scalar(s) => scalar_type(s).to_owned(),
        Shape::Message(m) => m.clone(),
        Shape::Map { key, value } => {
            let value = match value {
                Value::Scalar(s) => scalar_type(s).to_owned(),
                Value::Message(m) => m.clone(),
            };
            return format!("::std::collections::HashMap<{}, {value}>", scalar_type(key));
        }
    };
    match (&f.card, &f.shape) {
        (Card::Repeated { .. }, _) => format!("::prost::alloc::vec::Vec<{inner}>"),
        (Card::Optional, _) | (Card::Plain, Shape::Message(_)) => {
            format!("::core::option::Option<{inner}>")
        }
        (Card::Plain, _) => inner,
    }
}

fn is_set(s: &Scalar, field: &str) -> String {
    match s {
        Scalar::Plain("string" | "bytes", _, _) => format!("!self.{field}.is_empty()"),
        Scalar::Plain("bool", _, _) => format!("self.{field}"),
        Scalar::Plain(_, t, _) => format!("self.{field} != {t}::default()"),
        Scalar::Enum(_) => format!("self.{field} != 0"),
    }
}

/// The value prost-derive compares a proto3 implicit-presence scalar against.
fn is_default(s: &Scalar, field: &str) -> String {
    match s {
        Scalar::Plain("string" | "bytes", _, _) => format!("self.{field}.is_empty()"),
        Scalar::Plain("bool", _, _) => format!("!self.{field}"),
        Scalar::Plain(_, t, _) => format!("self.{field} == {t}::default()"),
        Scalar::Enum(_) => format!("self.{field} == 0"),
    }
}

fn map_fns(key: &Scalar, value: &Value, suffix: &str) -> String {
    let value_module = match value {
        Value::Scalar(s) => scalar_module(s),
        Value::Message(_) => "message",
    };
    format!(
        "::prost::encoding::{}::{suffix}, ::prost::encoding::{value_module}::{suffix}",
        scalar_module(key)
    )
}

fn encode(f: &Field) -> String {
    let (id, tag) = (&f.ident, f.tag);
    match (&f.shape, &f.card) {
        (Shape::Map { key, value }, _) => {
            let encode = map_fns(key, value, "encode");
            let len = map_fns(key, value, "encoded_len");
            let (ke, ve) = encode.split_once(", ").unwrap();
            let (kl, vl) = len.split_once(", ").unwrap();
            format!(
                "        ::prost::encoding::hash_map::encode({ke}, {kl}, {ve}, {vl}, {tag}, &self.{id}, buf);\n"
            )
        }
        (Shape::Message(_), Card::Repeated { .. }) => {
            format!(
                "        ::prost::encoding::message::encode_repeated({tag}, &self.{id}, buf);\n"
            )
        }
        (Shape::Message(_), _) => format!(
            "        if let ::core::option::Option::Some(ref value) = self.{id} {{\n\
             \x20           ::prost::encoding::message::encode({tag}, value, buf);\n\
             \x20       }}\n"
        ),
        (Shape::Scalar(s), Card::Repeated { packed }) => {
            let f = if *packed {
                "encode_packed"
            } else {
                "encode_repeated"
            };
            format!(
                "        ::prost::encoding::{}::{f}({tag}, &self.{id}, buf);\n",
                scalar_module(s)
            )
        }
        (Shape::Scalar(s), Card::Optional) => format!(
            "        if let ::core::option::Option::Some(ref value) = self.{id} {{\n\
             \x20           ::prost::encoding::{}::encode({tag}, value, buf);\n\
             \x20       }}\n",
            scalar_module(s)
        ),
        (Shape::Scalar(s), Card::Plain) => format!(
            "        if {} {{\n\
             \x20           ::prost::encoding::{}::encode({tag}, &self.{id}, buf);\n\
             \x20       }}\n",
            is_set(s, id),
            scalar_module(s)
        ),
    }
}

fn merge(f: &Field) -> String {
    let id = &f.ident;
    match (&f.shape, &f.card) {
        (Shape::Map { key, value }, _) => {
            let fns = map_fns(key, value, "merge");
            format!("::prost::encoding::hash_map::merge({fns}, &mut self.{id}, buf, ctx)")
        }
        (Shape::Message(_), Card::Repeated { .. }) => {
            format!("::prost::encoding::message::merge_repeated(wire_type, &mut self.{id}, buf, ctx)")
        }
        (Shape::Message(_), _) => format!(
            "::prost::encoding::message::merge(wire_type, self.{id}.get_or_insert_with(::core::default::Default::default), buf, ctx)"
        ),
        (Shape::Scalar(s), Card::Repeated { .. }) => format!(
            "::prost::encoding::{}::merge_repeated(wire_type, &mut self.{id}, buf, ctx)",
            scalar_module(s)
        ),
        (Shape::Scalar(s), Card::Optional) => format!(
            "::prost::encoding::{}::merge(wire_type, self.{id}.get_or_insert_with(::core::default::Default::default), buf, ctx)",
            scalar_module(s)
        ),
        (Shape::Scalar(s), Card::Plain) => format!(
            "::prost::encoding::{}::merge(wire_type, &mut self.{id}, buf, ctx)",
            scalar_module(s)
        ),
    }
}

fn encoded_len(f: &Field) -> String {
    let (id, tag) = (&f.ident, f.tag);
    match (&f.shape, &f.card) {
        (Shape::Map { key, value }, _) => {
            let fns = map_fns(key, value, "encoded_len");
            format!("::prost::encoding::hash_map::encoded_len({fns}, {tag}, &self.{id})")
        }
        (Shape::Message(_), Card::Repeated { .. }) => {
            format!("::prost::encoding::message::encoded_len_repeated({tag}, &self.{id})")
        }
        (Shape::Message(_), _) => format!(
            "self.{id}.as_ref().map_or(0, |value| ::prost::encoding::message::encoded_len({tag}, value))"
        ),
        (Shape::Scalar(s), Card::Repeated { packed }) => {
            let f = if *packed {
                "encoded_len_packed"
            } else {
                "encoded_len_repeated"
            };
            format!(
                "::prost::encoding::{}::{f}({tag}, &self.{id})",
                scalar_module(s)
            )
        }
        (Shape::Scalar(s), Card::Optional) => format!(
            "self.{id}.as_ref().map_or(0, |value| ::prost::encoding::{}::encoded_len({tag}, value))",
            scalar_module(s)
        ),
        (Shape::Scalar(s), Card::Plain) => format!(
            "if {} {{ 0 }} else {{ ::prost::encoding::{}::encoded_len({tag}, &self.{id}) }}",
            is_default(s, id),
            scalar_module(s)
        ),
    }
}

fn accessors(f: &Field) -> String {
    let (id, name) = (&f.ident, &f.name);
    let Shape::Scalar(s) = &f.shape else {
        return String::new();
    };
    match (s, &f.card) {
        (Scalar::Enum(e), Card::Plain) => format!(
            "    /// Returns the enum value of `{name}`, or the default if the field is set to an invalid enum value.\n\
             \x20   pub fn {id}(&self) -> {e} {{\n\
             \x20       ::core::convert::TryFrom::try_from(self.{id}).unwrap_or_default()\n\
             \x20   }}\n\
             \x20   /// Sets `{name}` to the provided enum value.\n\
             \x20   pub fn set_{name}(&mut self, value: {e}) {{\n\
             \x20       self.{id} = value as i32;\n\
             \x20   }}\n"
        ),
        (Scalar::Enum(e), Card::Optional) => format!(
            "    /// Returns the enum value of `{name}`, or the default if the field is unset or set to an invalid enum value.\n\
             \x20   pub fn {id}(&self) -> {e} {{\n\
             \x20       self.{id}\n\
             \x20           .and_then(|x| ::core::convert::TryFrom::try_from(x).ok())\n\
             \x20           .unwrap_or_default()\n\
             \x20   }}\n\
             \x20   /// Sets `{name}` to the provided enum value.\n\
             \x20   pub fn set_{name}(&mut self, value: {e}) {{\n\
             \x20       self.{id} = ::core::option::Option::Some(value as i32);\n\
             \x20   }}\n"
        ),
        (Scalar::Enum(e), Card::Repeated { .. }) => format!(
            "    /// Returns an iterator which yields the valid enum values contained in `{name}`.\n\
             \x20   pub fn {id}(&self) -> ::core::iter::FilterMap<\n\
             \x20       ::core::iter::Cloned<::core::slice::Iter<'_, i32>>,\n\
             \x20       fn(i32) -> ::core::option::Option<{e}>,\n\
             \x20   > {{\n\
             \x20       self.{id}\n\
             \x20           .iter()\n\
             \x20           .cloned()\n\
             \x20           .filter_map(|x| ::core::convert::TryFrom::try_from(x).ok())\n\
             \x20   }}\n\
             \x20   /// Appends the provided enum value to `{name}`.\n\
             \x20   pub fn push_{name}(&mut self, value: {e}) {{\n\
             \x20       self.{id}.push(value as i32);\n\
             \x20   }}\n"
        ),
        (Scalar::Plain(_, t, numeric), Card::Optional) => {
            let (ret, body) = match (*numeric, *t) {
                (true, t) => (t, "unwrap_or_default()"),
                (false, "::prost::alloc::string::String") => ("&str", "as_deref().unwrap_or_default()"),
                (false, _) => ("&[u8]", "as_deref().unwrap_or_default()"),
            };
            format!(
                "    /// Returns the value of `{name}`, or the default value if `{name}` is unset.\n\
                 \x20   pub fn {id}(&self) -> {ret} {{\n\
                 \x20       self.{id}.{body}\n\
                 \x20   }}\n"
            )
        }
        _ => String::new(),
    }
}

fn indent(doc: &str) -> String {
    doc.lines().map(|l| format!("    {l}\n")).collect()
}

/// Doc comments by descriptor path, rendered for rustdoc: leading and
/// trailing comments, brackets escaped, indentation flattened so no line
/// becomes a code block.
fn comments(file: &prost_types::FileDescriptorProto) -> HashMap<Vec<i32>, String> {
    let mut docs = HashMap::new();
    let Some(info) = &file.source_code_info else {
        return docs;
    };
    for location in &info.location {
        let split = |text: &str| -> Vec<String> {
            let text = text.strip_suffix('\n').unwrap_or(text);
            text.split('\n').map(sanitize).collect()
        };
        let mut lines = location
            .leading_comments
            .as_deref()
            .map_or(Vec::new(), split);
        if let Some(trailing) = &location.trailing_comments {
            if !lines.is_empty() {
                lines.push(String::new());
            }
            lines.extend(split(trailing));
        }
        if lines.is_empty() {
            continue;
        }
        let doc: String = lines
            .iter()
            .map(|l| {
                if l.is_empty() {
                    "///\n".to_owned()
                } else {
                    format!("/// {l}\n")
                }
            })
            .collect();
        docs.insert(location.path.clone(), doc);
    }
    docs
}

fn sanitize(line: &str) -> String {
    let mut out = String::new();
    let mut prev = ' ';
    for c in line.trim().chars() {
        match c {
            '[' | ']' if prev != '\\' => {
                out.push('\\');
                out.push(c);
            }
            _ => out.push(c),
        }
        prev = c;
    }
    out
}
